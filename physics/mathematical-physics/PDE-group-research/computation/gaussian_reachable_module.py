"""Exact preparation-reachable modules for finite Gaussian-rational actions."""

from __future__ import annotations

from dataclasses import dataclass

import exact_gaussian_matrix as gaussian
from exact_gaussian_linear import Vector, coordinates, linear_combination, matrix_vector


class ReachableModuleError(ValueError):
    def __init__(self, kind: str, reason: str):
        super().__init__(reason)
        self.kind = kind


@dataclass(frozen=True)
class ReachableModuleBudget:
    maximum_carrier_dimension: int
    maximum_active_dimension: int


@dataclass(frozen=True)
class Seed:
    pass


@dataclass(frozen=True)
class Apply:
    parent_index: int
    generator_index: int


type ReachableNode = Seed | Apply


@dataclass(frozen=True)
class ReachableModuleCost:
    generator_actions: int
    exact_coordinate_solves: int
    admitted_nodes: int
    rejected_dependent_actions: int


@dataclass(frozen=True)
class ReachableModule:
    basis: tuple[Vector, ...]
    provenance: tuple[ReachableNode, ...]
    reduced_actions: tuple[gaussian.ComplexMatrix, ...]
    cost: ReachableModuleCost
    checks: dict[str, bool]


def _standard_vector(dimension: int, selected: int) -> Vector:
    return tuple(gaussian.ONE if index == selected else gaussian.ZERO for index in range(dimension))


def _matrix_from_columns(columns: tuple[Vector, ...]) -> gaussian.ComplexMatrix:
    return tuple(
        tuple(columns[column][row] for column in range(len(columns)))
        for row in range(len(columns[0]))
    )


def _admit(
    generators: object, preparation: object, budget: ReachableModuleBudget
) -> tuple[tuple[gaussian.ComplexMatrix, ...], Vector]:
    bounds = (budget.maximum_carrier_dimension, budget.maximum_active_dimension)
    if any(isinstance(value, bool) or not isinstance(value, int) or value <= 0 for value in bounds):
        raise ReachableModuleError(
            "InvalidActiveSubspaceBudget", "bounds must be positive integers"
        )
    if not isinstance(generators, tuple) or not generators:
        raise ReachableModuleError("EmptyCoefficientFamily", "generator family must be nonempty")
    dimension = len(generators[0])
    if not dimension or any(
        not isinstance(matrix, tuple)
        or len(matrix) != dimension
        or any(not isinstance(row, tuple) or len(row) != dimension for row in matrix)
        or any(not isinstance(entry, gaussian.Gaussian) for row in matrix for entry in row)
        for matrix in generators
    ):
        raise ReachableModuleError(
            "CoefficientDimensionMismatch",
            "generators must be equal nonempty square exact matrices",
        )
    if dimension > budget.maximum_carrier_dimension:
        raise ReachableModuleError("CarrierBudgetExceeded", "carrier dimension exceeds budget")
    if (
        not isinstance(preparation, tuple)
        or len(preparation) != dimension
        or any(not isinstance(entry, gaussian.Gaussian) for entry in preparation)
    ):
        raise ReachableModuleError(
            "PreparationDimensionMismatch", f"preparation must have exact dimension {dimension}"
        )
    if all(entry == gaussian.ZERO for entry in preparation):
        raise ReachableModuleError("ZeroPreparation", "preparation must be nonzero")
    return generators, preparation


def construct_reachable_module(
    generators: tuple[gaussian.ComplexMatrix, ...],
    preparation: Vector,
    budget: ReachableModuleBudget,
) -> ReachableModule:
    """Construct the deterministic cyclic module generated by `preparation`."""
    generators, preparation = _admit(generators, preparation, budget)
    basis = [preparation]
    provenance: list[ReachableNode] = [Seed()]
    records: list[list[Vector | int]] = []
    images: list[list[Vector]] = []
    rejected = 0
    parent = 0
    while parent < len(basis):
        parent_records: list[Vector | int] = []
        parent_images: list[Vector] = []
        for generator_index, generator in enumerate(generators):
            image = matrix_vector(generator, basis[parent])
            parent_images.append(image)
            coordinate = coordinates(image, tuple(basis))
            if coordinate is None:
                if len(basis) >= budget.maximum_active_dimension:
                    raise ReachableModuleError(
                        "ActiveSubspaceBudgetExceeded",
                        "generator-family closure exceeds active-dimension budget",
                    )
                basis.append(image)
                provenance.append(Apply(parent, generator_index))
                parent_records.append(len(basis) - 1)
            else:
                rejected += 1
                parent_records.append(coordinate)
        records.append(parent_records)
        images.append(parent_images)
        parent += 1

    active_basis = tuple(basis)
    active_dimension = len(active_basis)

    def final_coordinate(record: Vector | int) -> Vector:
        if isinstance(record, int):
            return _standard_vector(active_dimension, record)
        return (*record, *(gaussian.ZERO for _ in range(active_dimension - len(record))))

    reduced_actions = tuple(
        _matrix_from_columns(
            tuple(final_coordinate(records[parent][index]) for parent in range(active_dimension))
        )
        for index in range(len(generators))
    )
    checks = {
        "basis_starts_at_preparation": active_basis[0] == preparation,
        "provenance_is_parent_ordered": all(
            isinstance(node, Seed) or node.parent_index < index
            for index, node in enumerate(provenance)
        ),
        "every_generator_closes_on_basis": all(
            linear_combination(
                tuple(reduced[row][column] for row in range(active_dimension)), active_basis
            )
            == images[column][generator_index]
            for generator_index, reduced in enumerate(reduced_actions)
            for column in range(active_dimension)
        ),
    }
    if not all(checks.values()):
        failed = next(name for name, passed in checks.items() if not passed)
        raise ReachableModuleError("ReachableModuleResidual", f"construction fails at {failed}")
    actions = len(generators) * active_dimension
    return ReachableModule(
        active_basis,
        tuple(provenance),
        reduced_actions,
        ReachableModuleCost(actions, actions, active_dimension, rejected),
        checks,
    )
